#!/usr/bin/env python3
"""Verify the generated UTS catalogs used by native uni-app x runtimes."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/core/i18n/generated/catalog-entries.uts"


def load_catalog(locale: str) -> dict[str, str]:
    path = ROOT / "locale" / f"{locale}.json"
    with path.open(encoding="utf-8") as source:
        value = json.load(source)
    if not isinstance(value, dict) or not all(
        isinstance(key, str) and isinstance(text, str) and text for key, text in value.items()
    ):
        raise SystemExit(f"invalid locale catalog: {path}")
    return value


def uts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_entries(name: str, values: dict[str, str]) -> list[str]:
    lines = [f"export const {name}: Array<string> = ["]
    for key, value in values.items():
        lines.append(f"  {uts_string(key)},")
        lines.append(f"  {uts_string(value)},")
    lines.append("]")
    return lines


def render() -> str:
    zh_cn = load_catalog("zh-CN")
    en_us = load_catalog("en-US")
    if zh_cn.keys() != en_us.keys():
        raise SystemExit("zh-CN/en-US locale keys differ")
    lines = [
        "// Generated from locale/*.json by scripts/check-i18n-catalogs.py.",
        "// Do not edit this file directly.",
        "",
        *render_entries("zhCNEntries", zh_cn),
        "",
        *render_entries("enUSEntries", en_us),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--print", action="store_true", dest="print_output")
    parser.add_argument("--write", action="store_true", dest="write_output")
    args = parser.parse_args()
    expected = render()
    if args.print_output and args.write_output:
        parser.error("--print and --write are mutually exclusive")
    if args.print_output:
        print(expected, end="")
        return
    if args.write_output:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"updated {OUTPUT.relative_to(ROOT)}")
        return
    actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if actual != expected:
        raise SystemExit(
            "generated mobile i18n catalog is stale; run "
            "python3 scripts/check-i18n-catalogs.py --write"
        )
    print("mobile generated i18n catalogs are current")


if __name__ == "__main__":
    main()
