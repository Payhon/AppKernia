#!/usr/bin/env python3
"""Generate a typed UTS-safe string wrapper for the exported OAuth snapshot.

uni-app x turns imported JSON into TypeScript before UTS compilation. An
exported App with no providers contains empty arrays, which Kotlin type
inference cannot compile. Keeping the audited JSON as the build/export source
and embedding its canonical serialization in a typed string avoids that
platform-specific inference failure without adding a permissive placeholder.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config/login-providers.generated.json"
OUTPUT = ROOT / "src/generated/oauth-bundled-snapshot.uts"


def render() -> str:
    value = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise SystemExit("OAuth provider snapshot must be an object")
    canonical = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    literal = json.dumps(canonical, ensure_ascii=False)
    return (
        "// Generated from config/login-providers.generated.json by "
        "scripts/generate-oauth-snapshot-uts.py.\n"
        "// Do not edit this file directly.\n\n"
        f"export const oauthBundledSnapshotJSON: string = {literal}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"updated {OUTPUT.relative_to(ROOT)}")
        return
    actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
    if actual != expected:
        raise SystemExit(
            "generated OAuth snapshot wrapper is stale; run "
            "python3 scripts/generate-oauth-snapshot-uts.py --write"
        )
    print("mobile OAuth bundled snapshot wrapper is current")


if __name__ == "__main__":
    main()
